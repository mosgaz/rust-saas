#![allow(clippy::type_complexity)]
//! Integration tests for `audit-pg` against a real PostgreSQL.
//!
//! `#[sqlx::test]` creates an isolated database per test, applies
//! `crates/db/migrations` (including `audit_log`), and drops it afterwards.
//!
//! `PgAuditLogger::from_pool` shares the test pool, so audit rows live in
//! that test database.

use audit::{events, AuditEvent, AuditLogger};
use audit_pg::PgAuditLogger;
use chrono::{DateTime, Utc};
use sqlx::PgPool;
use uuid::Uuid;

#[sqlx::test(migrations = "../db/migrations")]
async fn log_persists_row(pool: PgPool) {
    // Create an actor so the FK can be satisfied.
    let actor_id: Uuid = sqlx::query_scalar(
        r#"
        insert into users (email, password_hash)
        values ($1, 'hash')
        returning id
        "#,
    )
    .bind(format!("actor-{}@test.local", Uuid::new_v4()))
    .fetch_one(&pool)
    .await
    .unwrap();

    let logger = PgAuditLogger::from_pool(pool.clone());

    let mut ev = AuditEvent::new(events::TENANT_CREATED);
    ev.actor_id = Some(actor_id);
    ev.actor_email = Some("owner@acme.test".to_string());
    ev.target_type = Some("tenant".to_string());
    ev.target_id = Some(Uuid::new_v4());
    ev.metadata = serde_json::json!({ "name": "Acme" });

    logger.log(&ev).await.expect("log must succeed");

    let row: (
        Uuid,
        DateTime<Utc>,
        Option<Uuid>,
        Option<String>,
        String,
        Option<String>,
        Option<Uuid>,
        serde_json::Value,
    ) = sqlx::query_as(
        r#"
            select id, occurred_at, actor_id, actor_email, event_type,
                   target_type, target_id, metadata
            from audit_log
            "#,
    )
    .fetch_one(&pool)
    .await
    .unwrap();

    let (
        id,
        occurred_at,
        actor_id_db,
        actor_email_db,
        event_type,
        target_type,
        target_id_db,
        metadata,
    ) = row;
    assert!(!id.is_nil(), "id must be generated by the DB");
    assert!(
        (Utc::now() - occurred_at).num_seconds().abs() < 60,
        "occurred_at must default to now()"
    );
    assert_eq!(actor_id_db, Some(actor_id));
    assert_eq!(actor_email_db.as_deref(), Some("owner@acme.test"));
    assert_eq!(event_type, "tenant.created");
    assert_eq!(target_type.as_deref(), Some("tenant"));
    assert_eq!(target_id_db, ev.target_id);
    assert_eq!(metadata, serde_json::json!({ "name": "Acme" }));
}

#[sqlx::test(migrations = "../db/migrations")]
async fn log_metadata_roundtrips_jsonb(pool: PgPool) {
    let logger = PgAuditLogger::from_pool(pool.clone());

    let mut ev = AuditEvent::new(events::MEMBER_ROLE_ASSIGNED);
    ev.metadata = serde_json::json!({
        "role_key": "editor",
        "scope": "workspace:abc",
        "nested": { "a": 1, "b": [1, 2, 3] },
    });

    logger.log(&ev).await.unwrap();

    let stored: serde_json::Value = sqlx::query_scalar("select metadata from audit_log")
        .fetch_one(&pool)
        .await
        .unwrap();

    assert_eq!(stored, ev.metadata);
    assert_eq!(stored["role_key"], "editor");
    assert_eq!(stored["nested"]["b"][1], 2);

    // Default `{}` for events that do not set metadata.
    let mut ev2 = AuditEvent::new(events::USER_LOGOUT);
    ev2.metadata = serde_json::json!({});
    logger.log(&ev2).await.unwrap();

    let defaults: serde_json::Value =
        sqlx::query_scalar("select metadata from audit_log where event_type = 'user.logout'")
            .fetch_one(&pool)
            .await
            .unwrap();
    assert_eq!(defaults, serde_json::json!({}));
}

#[sqlx::test(migrations = "../db/migrations")]
async fn log_actor_id_nullable(pool: PgPool) {
    let logger = PgAuditLogger::from_pool(pool.clone());

    // System / anonymous event: `actor_id = None`, `actor_email` set.
    let mut ev = AuditEvent::new(events::USER_LOGIN_FAILED);
    ev.actor_id = None;
    ev.actor_email = Some("unknown@test.local".to_string());
    ev.metadata = serde_json::json!({ "reason": "invalid_credentials" });

    logger.log(&ev).await.expect("system event must succeed");

    let row: (Option<Uuid>, Option<String>, String) =
        sqlx::query_as("select actor_id, actor_email, event_type from audit_log")
            .fetch_one(&pool)
            .await
            .unwrap();
    assert!(row.0.is_none(), "actor_id must be NULL for system events");
    assert_eq!(row.1.as_deref(), Some("unknown@test.local"));
    assert_eq!(row.2, "user.login_failed");
}

#[sqlx::test(migrations = "../db/migrations")]
async fn log_actor_id_on_delete_set_null(pool: PgPool) {
    let actor_id: Uuid = sqlx::query_scalar(
        r#"
        insert into users (email, password_hash)
        values ($1, 'hash')
        returning id
        "#,
    )
    .bind(format!("doomed-{}@test.local", Uuid::new_v4()))
    .fetch_one(&pool)
    .await
    .unwrap();

    let logger = PgAuditLogger::from_pool(pool.clone());

    let mut ev = AuditEvent::new(events::USER_REGISTERED);
    ev.actor_id = Some(actor_id);
    ev.actor_email = Some("doomed@test.local".to_string());
    logger.log(&ev).await.unwrap();

    // Delete the user: FK is `ON DELETE SET NULL`, row survives.
    sqlx::query("delete from users where id = $1")
        .bind(actor_id)
        .execute(&pool)
        .await
        .unwrap();

    let count: i64 = sqlx::query_scalar("select count(*) from audit_log")
        .fetch_one(&pool)
        .await
        .unwrap();
    assert_eq!(count, 1, "audit row must survive user deletion");

    let row: (Option<Uuid>, Option<String>) =
        sqlx::query_as("select actor_id, actor_email from audit_log")
            .fetch_one(&pool)
            .await
            .unwrap();
    assert!(row.0.is_none(), "actor_id must become NULL");
    assert_eq!(
        row.1.as_deref(),
        Some("doomed@test.local"),
        "denormalized actor_email must survive"
    );
}
// ─── Stage 4.3c: per-crate MIGRATOR ────────────────────────────────────────

/// `audit_pg::MIGRATOR` builds the schema a standalone consumer needs:
/// `000_users_bootstrap.sql` (FK target for `audit_log.actor_id`) and
/// `001_audit_log.sql` (table + indexes). `#[sqlx::test]` (no `migrations = …`)
/// gives an **empty** database — exactly what a partial consumer starts
/// from.
///
/// Composition with `db::migrate` is *not* tested here on purpose: sqlx
/// rejects mixing two `Migrator`s on one database (`VersionMissing`), and
/// `crates/db/src/lib.rs::migrate_with` documents that a consumer picks
/// one path per database.
#[sqlx::test]
async fn migrator_builds_standalone_schema(pool: PgPool) {
    audit_pg::MIGRATOR
        .run(&pool)
        .await
        .expect("per-crate MIGRATOR must build audit_log + users bootstrap");

    // `users` exists (migration `000_…`).
    let has_users: bool = sqlx::query_scalar(
        "select exists (select 1 from information_schema.tables where table_name = 'users')",
    )
    .fetch_one(&pool)
    .await
    .unwrap();
    assert!(has_users, "000_users_bootstrap must have run");

    // `audit_log` exists (migration `001_…`).
    let has_audit: bool = sqlx::query_scalar(
        "select exists (select 1 from information_schema.tables where table_name = 'audit_log')",
    )
    .fetch_one(&pool)
    .await
    .unwrap();
    assert!(has_audit, "001_audit_log must have run");

    // End-to-end: an insert via `PgAuditLogger` lands in `audit_log`.
    let logger = PgAuditLogger::from_pool(pool.clone());
    logger
        .log(&AuditEvent::new("stage4_3c.standalone"))
        .await
        .expect("insert via standalone schema");

    let count: i64 = sqlx::query_scalar(
        "select count(*) from audit_log where event_type = 'stage4_3c.standalone'",
    )
    .fetch_one(&pool)
    .await
    .unwrap();
    assert_eq!(count, 1);
}

/// `MIGRATOR` is idempotent: a second `run()` against the same database is
/// a no-op (sqlx skips versions already recorded in `_sqlx_migrations`).
/// This is *within* one migrator, not composition with `db::migrate`.
#[sqlx::test]
async fn migrator_is_idempotent_on_repeat_run(pool: PgPool) {
    audit_pg::MIGRATOR
        .run(&pool)
        .await
        .expect("first MIGRATOR run");
    audit_pg::MIGRATOR
        .run(&pool)
        .await
        .expect("second MIGRATOR run must be a no-op");

    let versions: i64 =
        sqlx::query_scalar("select count(*) from _sqlx_migrations where success = true")
            .fetch_one(&pool)
            .await
            .unwrap();
    assert_eq!(
        versions, 2,
        "exactly the two per-crate migrations (000, 001) must be recorded"
    );
}

// ─── Stage 4.8: Pagination ─────────────────────────────────────────────────

#[sqlx::test(migrations = "../db/migrations")]
async fn list_paged_works(pool: PgPool) {
    let logger = PgAuditLogger::from_pool(pool.clone());

    // Insert 5 events
    for i in 0..5 {
        let mut ev = AuditEvent::new(format!("test.event_{}", i));
        ev.metadata = serde_json::json!({ "idx": i });
        logger.log(&ev).await.unwrap();
    }

    // Page 1: limit 2, offset 0
    let page1 = logger.list_paged(2, 0).await.unwrap();
    assert_eq!(page1.total, 5);
    assert_eq!(page1.items.len(), 2);
    assert_eq!(page1.items[0].event_type, "test.event_4"); // newest first
    assert_eq!(page1.items[1].event_type, "test.event_3");

    // Page 2: limit 2, offset 2
    let page2 = logger.list_paged(2, 2).await.unwrap();
    assert_eq!(page2.total, 5);
    assert_eq!(page2.items.len(), 2);
    assert_eq!(page2.items[0].event_type, "test.event_2");

    // Offset beyond total
    let page3 = logger.list_paged(2, 10).await.unwrap();
    assert_eq!(page3.total, 5);
    assert!(page3.items.is_empty());
}
