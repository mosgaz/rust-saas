//! Integration tests for `audit-pg` against a real PostgreSQL.
//!
//! `#[sqlx::test]` creates an isolated database per test, applies
//! `crates/db/migrations` (including `audit_log`), and drops it afterwards.
//!
//! `PgAuditLogger::from_pool` shares the test pool, so audit rows live in
//! that test database.

use audit::{events, AuditEvent, AuditLogger};
use audit_pg::PgAuditLogger;
use chrono::{DateTime, Utc};
use sqlx::PgPool;
use uuid::Uuid;

#[sqlx::test(migrations = "../db/migrations")]
async fn log_persists_row(pool: PgPool) {
    // Create an actor so the FK can be satisfied.
    let actor_id: Uuid = sqlx::query_scalar(
        r#"
        insert into users (email, password_hash)
        values ($1, 'hash')
        returning id
        "#,
    )
    .bind(format!("actor-{}@test.local", Uuid::new_v4()))
    .fetch_one(&pool)
    .await
    .unwrap();

    let logger = PgAuditLogger::from_pool(pool.clone());

    let mut ev = AuditEvent::new(events::TENANT_CREATED);
    ev.actor_id = Some(actor_id);
    ev.actor_email = Some("owner@acme.test".to_string());
    ev.target_type = Some("tenant".to_string());
    ev.target_id = Some(Uuid::new_v4());
    ev.metadata = serde_json::json!({ "name": "Acme" });

    logger.log(&ev).await.expect("log must succeed");

    let row: (Uuid, DateTime<Utc>, Option<Uuid>, Option<String>, String, Option<String>, Option<Uuid>, serde_json::Value) =
        sqlx::query_as(
            r#"
            select id, occurred_at, actor_id, actor_email, event_type,
                   target_type, target_id, metadata
            from audit_log
            "#,
        )
        .fetch_one(&pool)
        .await
        .unwrap();

    let (id, occurred_at, actor_id_db, actor_email_db, event_type, target_type, target_id_db, metadata) = row;
    assert!(!id.is_nil(), "id must be generated by the DB");
    assert!(
        (Utc::now() - occurred_at).num_seconds().abs() < 60,
        "occurred_at must default to now()"
    );
    assert_eq!(actor_id_db, Some(actor_id));
    assert_eq!(actor_email_db.as_deref(), Some("owner@acme.test"));
    assert_eq!(event_type, "tenant.created");
    assert_eq!(target_type.as_deref(), Some("tenant"));
    assert_eq!(target_id_db, ev.target_id);
    assert_eq!(metadata, serde_json::json!({ "name": "Acme" }));
}

#[sqlx::test(migrations = "../db/migrations")]
async fn log_metadata_roundtrips_jsonb(pool: PgPool) {
    let logger = PgAuditLogger::from_pool(pool.clone());

    let mut ev = AuditEvent::new(events::MEMBER_ROLE_ASSIGNED);
    ev.metadata = serde_json::json!({
        "role_key": "editor",
        "scope": "workspace:abc",
        "nested": { "a": 1, "b": [1, 2, 3] },
    });

    logger.log(&ev).await.unwrap();

    let stored: serde_json::Value =
        sqlx::query_scalar("select metadata from audit_log")
            .fetch_one(&pool)
            .await
            .unwrap();

    assert_eq!(stored, ev.metadata);
    assert_eq!(stored["role_key"], "editor");
    assert_eq!(stored["nested"]["b"][1], 2);

    // Default `{}` for events that do not set metadata.
    let mut ev2 = AuditEvent::new(events::USER_LOGOUT);
    ev2.metadata = serde_json::json!({});
    logger.log(&ev2).await.unwrap();

    let defaults: serde_json::Value =
        sqlx::query_scalar("select metadata from audit_log where event_type = 'user.logout'")
            .fetch_one(&pool)
            .await
            .unwrap();
    assert_eq!(defaults, serde_json::json!({}));
}

#[sqlx::test(migrations = "../db/migrations")]
async fn log_actor_id_nullable(pool: PgPool) {
    let logger = PgAuditLogger::from_pool(pool.clone());

    // System / anonymous event: `actor_id = None`, `actor_email` set.
    let mut ev = AuditEvent::new(events::USER_LOGIN_FAILED);
    ev.actor_id = None;
    ev.actor_email = Some("unknown@test.local".to_string());
    ev.metadata = serde_json::json!({ "reason": "invalid_credentials" });

    logger.log(&ev).await.expect("system event must succeed");

    let row: (Option<Uuid>, Option<String>, String) =
        sqlx::query_as("select actor_id, actor_email, event_type from audit_log")
            .fetch_one(&pool)
            .await
            .unwrap();
    assert!(row.0.is_none(), "actor_id must be NULL for system events");
    assert_eq!(row.1.as_deref(), Some("unknown@test.local"));
    assert_eq!(row.2, "user.login_failed");
}

#[sqlx::test(migrations = "../db/migrations")]
async fn log_actor_id_on_delete_set_null(pool: PgPool) {
    let actor_id: Uuid = sqlx::query_scalar(
        r#"
        insert into users (email, password_hash)
        values ($1, 'hash')
        returning id
        "#,
    )
    .bind(format!("doomed-{}@test.local", Uuid::new_v4()))
    .fetch_one(&pool)
    .await
    .unwrap();

    let logger = PgAuditLogger::from_pool(pool.clone());

    let mut ev = AuditEvent::new(events::USER_REGISTERED);
    ev.actor_id = Some(actor_id);
    ev.actor_email = Some("doomed@test.local".to_string());
    logger.log(&ev).await.unwrap();

    // Delete the user: FK is `ON DELETE SET NULL`, row survives.
    sqlx::query("delete from users where id = $1")
        .bind(actor_id)
        .execute(&pool)
        .await
        .unwrap();

    let count: i64 = sqlx::query_scalar("select count(*) from audit_log")
        .fetch_one(&pool)
        .await
        .unwrap();
    assert_eq!(count, 1, "audit row must survive user deletion");

    let row: (Option<Uuid>, Option<String>) =
        sqlx::query_as("select actor_id, actor_email from audit_log")
            .fetch_one(&pool)
            .await
            .unwrap();
    assert!(row.0.is_none(), "actor_id must become NULL");
    assert_eq!(
        row.1.as_deref(),
        Some("doomed@test.local"),
        "denormalized actor_email must survive"
    );
}